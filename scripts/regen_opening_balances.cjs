const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const recs = JSON.parse(fs.readFileSync(path.join(ROOT, 'server', 'seeds', 'receivables_pdf_152_final.json'), 'utf8'));
const cust = JSON.parse(fs.readFileSync(path.join(ROOT, 'server', 'seeds', 'customers_pdf_343.json'), 'utf8'));

const norm = (s) => String(s || '').replace(/[^a-z0-9]/gi, '').toLowerCase();
const codeByTitle = new Map();
for (const c of cust) codeByTitle.set(norm(c.accountTitle), c.code);

const entries = recs
  .map((r) => ({
    key: norm(r.title),
    code: codeByTitle.get(norm(r.title)) || '',
    title: r.title,
    openingBalance: Math.round(Number(r.balance) * 100) / 100,
    openingBalanceType: r.balanceType,
    sNo: r.sNo,
  }))
  .sort((a, b) => a.sNo - b.sNo);

const dupes = entries.filter((e, i) => entries.findIndex((x) => x.key === e.key) !== i);
if (dupes.length) throw new Error('duplicate keys: ' + dupes.map((d) => d.key).join(','));
const noCode = entries.filter((e) => !e.code);
if (noCode.length) throw new Error('no customer code for: ' + noCode.map((d) => d.title).join(', '));

const lines = entries.map((e) => {
  const title = e.title.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return `  "${e.key}": {\n    "code": "${e.code}",\n    "title": "${title}",\n    "openingBalance": ${e.openingBalance},\n    "openingBalanceType": "${e.openingBalanceType}"\n  },`;
});

const out = `// Master Authoritative Customer Opening Balances Mapping
// Source of truth: reciveballe.pdf (Party Receivable Report, 21-10-2026)
// Regenerated by scripts/regen_opening_balances.js - ${entries.length} rows.
export interface CustomerOpeningRecord {
  code: string;
  title: string;
  openingBalance: number;
  openingBalanceType: 'DR' | 'CR';
}

export const MASTER_CUSTOMER_OPENING_BALANCES: Record<string, CustomerOpeningRecord> = {
${lines.join('\n')}
};
`;

const dest = path.join(ROOT, 'server', 'customerOpeningBalances.ts');
fs.writeFileSync(dest, out, 'utf8');
const dr = entries.filter((e) => e.openingBalanceType === 'DR').reduce((a, e) => a + e.openingBalance, 0);
const cr = entries.filter((e) => e.openingBalanceType === 'CR').reduce((a, e) => a + e.openingBalance, 0);
console.log(`[regen] ${entries.length} entries -> server/customerOpeningBalances.ts`);
console.log(`[regen] DR ${dr.toFixed(2)} - CR ${cr.toFixed(2)} = NET ${(dr - cr).toFixed(2)}`);
